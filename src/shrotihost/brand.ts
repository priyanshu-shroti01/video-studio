// Brand fonts (OFL), self-hosted from public/fonts: latin + latin-ext (latin-ext carries ₹ U+20B9).
const FACES: [string, string, string][] = [
  ['Plus Jakarta Sans', 'fonts/jakarta-latin.woff2', 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD'],
  ['Plus Jakarta Sans', 'fonts/jakarta-latin-ext.woff2', 'U+0100-02BA,U+1E00-1EFF,U+20A0-20AB,U+20AD-20C4,U+2113'],
  ['Geist Mono', 'fonts/geistmono-latin.woff2', 'U+0000-00FF,U+0131,U+0152-0153,U+2000-206F,U+20AC,U+2122,U+2212'],
  ['Geist Mono', 'fonts/geistmono-latin-ext.woff2', 'U+0100-02BA,U+20A0-20AB,U+20AD-20C4'],
];
let fontsRequested = false;
export const loadBrandFonts = () => {
  if (fontsRequested || typeof document === 'undefined') return;
  fontsRequested = true;
  const handle = delayRender('Loading brand fonts');
  Promise.all(
    FACES.map(([family, file, unicodeRange]) =>
      new FontFace(family, `url(${staticFile(file)}) format('woff2')`, {weight: '200 800', unicodeRange})
        .load()
        .then((f) => document.fonts.add(f)),
    ),
  )
    .then(() => continueRender(handle))
    .catch((e) => cancelRender(e));
};

